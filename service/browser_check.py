"""Manual-invocation browser integration check; use an isolated server data dir."""
from pathlib import Path
import os
from playwright.sync_api import sync_playwright

with sync_playwright() as p:
    browser=p.chromium.launch(channel='chrome',headless=True)
    page=browser.new_page(viewport={'width':1440,'height':1100})
    page.set_default_timeout(15000)
    errors=[]
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.on('console',lambda m:errors.append(m.text) if m.type=='error' else None)
    page.goto(os.getenv('WOUNDWATCH_TEST_URL','http://127.0.0.1:8000'))
    page.get_by_role('heading',name='Overview',exact=True).wait_for()
    Path('test-results').mkdir(exist_ok=True)
    page.screenshot(path='test-results/overview-desktop.png',full_page=True)
    page.locator('nav a[href="#patients"]').click()
    page.locator('[data-add]').first.click()
    form=page.locator('#patient-form')
    form.locator('[name=name]').fill('Browser research alias')
    form.locator('[name=age]').fill('45')
    form.locator('[name=surgery_type]').fill('Execution test')
    form.locator('[name=surgery_date]').fill('2026-01-01')
    form.locator('[name=wound_location]').fill('Research wound')
    form.get_by_role('button',name='Save patient').click()
    page.locator('#patient-dialog').wait_for(state='hidden')
    page.locator('nav a[href="#scans"]').click()
    page.locator('#image-file').set_input_files('data/raw/surgwound/images/train/02b44effbbf2.jpg')
    page.locator('#scan-form [name=scan_date]').fill('2026-01-02')
    with page.expect_response(lambda r: r.url.endswith('/api/scans') and r.request.method=='POST',timeout=60000) as uploaded:
        page.locator('#analyse-button').click()
    assert uploaded.value.status==201, uploaded.value.text()
    page.get_by_role('heading',name='AI analysis',exact=True).wait_for(timeout=60000)
    print('First analysis page reached',flush=True)
    page.get_by_text('42.0%',exact=True).wait_for()
    page.screenshot(path='test-results/analysis-desktop.png',full_page=True)
    page.locator('nav a[href="#scans"]').click()
    page.locator('#scan-form [name=scan_date]').fill('2026-01-03')
    page.locator('#scan-form [name=scan_date]').dispatch_event('change')
    page.locator('#previous-scan').select_option(index=1)
    page.locator('#image-file').set_input_files('data/raw/surgwound/images/train/02b44effbbf2.jpg')
    with page.expect_response(lambda r: r.url.endswith('/api/scans') and r.request.method=='POST',timeout=60000) as uploaded:
        page.locator('#analyse-button').click()
    assert uploaded.value.status==201, uploaded.value.text()
    page.get_by_role('heading',name='AI analysis',exact=True).wait_for(timeout=60000)
    page.locator('nav a[href="#colour"]').click()
    page.get_by_role('heading',name='Current colour measurements').wait_for()
    for kind in ('colour','gradcam'):
        page.locator(f'[data-visual={kind}]').click()
        page.locator(f'[data-visual={kind}]').locator('..').locator('.visual-output img').wait_for(timeout=60000)
    page.screenshot(path='test-results/colour-gradcam.png',full_page=True)
    page.locator('#colour-previous').select_option(index=0)
    page.locator('#save-comparison').click()
    page.get_by_text('Comparison updated.',exact=True).wait_for()
    page.locator('#colour-previous').select_option(index=1)
    page.locator('#save-comparison').click()
    page.wait_for_timeout(300)
    page.locator('#recalculate-colour').click()
    page.get_by_text('Colour measurements recalculated. Screening result preserved.',exact=True).wait_for(timeout=60000)
    page.locator('nav a[href="#history"]').click()
    page.locator('#compare-a').select_option(index=1)
    page.locator('#compare-b').select_option(index=2)
    page.locator('#compare').click()
    page.locator('#comparison img').first.wait_for()
    page.locator('nav a[href="#reports"]').click()
    with page.expect_download() as d:
        page.locator('#download-report').click()
    assert d.value.suggested_filename.endswith('.json')
    page.emulate_media(media='print')
    page.pdf(path='test-results/report.pdf')
    page.emulate_media(media='screen')
    for key in ['patients','risk','notifications','settings','overview']:
        page.locator(f'nav a[href="#{key}"]').click()
    page.set_viewport_size({'width':390,'height':844})
    page.screenshot(path='test-results/overview-mobile.png',full_page=True)
    assert page.evaluate('document.documentElement.scrollWidth <= innerWidth'), 'Mobile overflow'
    page.locator('#menu').click()
    page.locator('nav a[href="#patients"]').click()
    page.get_by_role('heading',name='Patients',exact=True).wait_for()
    assert not errors, errors
    print('PASS: patient creation, actual inference, comparison, navigation, JSON/PDF reports, mobile layout; no console/page errors')
    browser.close()
